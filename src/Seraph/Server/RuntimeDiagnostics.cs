internal sealed record CompatibilityArchive(string File, string ModId, string Version, string Name, string Sha256, string Policy,
    string Status = "untested", string Scope = "target", Dictionary<string, string>? Dependencies = null,
    [property: JsonConverter(typeof(OneOrManyStringsConverter))] string[]? IntegrationDomains = null, string? Description = null, string? SeraphHandling = null,
    string? CapabilityOwner = null, string? Acceptance = null, string? Evidence = null);
internal sealed record RuntimeFeature(string Id, bool PolicyEnabled, int InstalledHookCount, bool Ready, string Scope);

// Catalogs generated by older PowerShell versions may contain a scalar for a single domain.
internal sealed class OneOrManyStringsConverter : JsonConverter<string[]>
{
    public override string[]? Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options)
        => reader.TokenType == JsonTokenType.String ? [reader.GetString()!]
            : JsonSerializer.Deserialize<string[]>(ref reader, options);
    public override void Write(Utf8JsonWriter writer, string[] value, JsonSerializerOptions options)
        => JsonSerializer.Serialize(writer, value, options);
}

internal sealed class RuntimeDiagnostics : IDisposable
{
    private readonly ICoreServerAPI api;
    private readonly string directory;
    private readonly long maxBytes;
    private StreamWriter? csv;
    private bool csvDisabled;
    private int records;
    private long rounds;
    private double totalRoundMs;
    private double maxRoundMs;
    private int maxPlayers;
    public string[] IntegrationLines { get; private set; } = [];

    public void RecordRound(double milliseconds, int players)
    {
        if (!double.IsFinite(milliseconds) || milliseconds < 0) return;
        rounds++;
        totalRoundMs += milliseconds;
        maxRoundMs = Math.Max(maxRoundMs, milliseconds);
        maxPlayers = Math.Max(maxPlayers, players);
    }

    public void WritePerformance()
    {
        try
        {
            File.WriteAllText(Path.Combine(directory, "performance-runtime.json"), JsonSerializer.Serialize(new
            {
                Package = "vsslssmod", Version = Seraph.Core.BuildInfo.Version, Rounds = rounds,
                MeanRoundMs = rounds == 0 ? 0 : totalRoundMs / rounds, MaxRoundMs = maxRoundMs,
                MaxPlayers = maxPlayers, Scope = "whole coordinator callback including sampling and publishing",
                LoadTestPerformed = false
            }, new JsonSerializerOptions { WriteIndented = true }));
        }
        catch (Exception ex) { api.Logger.Warning("[vsslssmod] Performance report unavailable: {0}", ex.Message); }
    }

    public RuntimeDiagnostics(ICoreServerAPI api, int maxMiB)
    {
        this.api = api;
        directory = api.GetOrCreateDataPath("vsslssmod");
        maxBytes = maxMiB * 1024L * 1024;
    }

    internal static RuntimeFeature[] RuntimeFeatures(CapabilityRegistry owners, SeraphServerConfig config)
    {
        var patched = Harmony.GetAllPatchedMethods().Select(m => (Method: m, Owners: Harmony.GetPatchInfo(m)?.Owners.ToArray() ?? [])).ToArray();
        RuntimeFeature Feature(string id, bool policy, string harmonyId, string scope, string? declaringType = null,
            bool extraReady = true)
        {
            var count = patched.Count(p => p.Owners.Contains(harmonyId)
                && (declaringType is null || p.Method.DeclaringType?.FullName == declaringType));
            return new(id, policy, count, policy && count > 0 && extraReady, scope);
        }
        var active = config.Mode == "survival";
        return [
            Feature("human-vehicle-control", active && config.EnableInjuryActionEffects && owners.MayWrite(Capability.Health),
                "vsslssmod.vehicles", "native permission gates, human cart drive and validated optional manual-control adapters",
                extraReady: NativeVehicleBridge.NativeReady),
            Feature("native-physiology", active && owners.MayWrite(Capability.Health), "vsslssmod.physiology", "regional health and native hunger projection"),
            Feature("finite-native-care", active && config.EnableMedicalActions && config.EnableClinicalEffects
                && owners.MayWrite(Capability.BleedingDamage), "vsslssmod.bandages", "native bandages/poultices; item debit and checkpoint rollback"),
            Feature("oxygen-recovery", active && owners.MayWrite(Capability.Health), "vsslssmod.injury-actions", "native oxygen only; no parallel oxygen reserve",
                typeof(Vintagestory.GameContent.EntityBehaviorBreathe).FullName, NativeInjuryActionBridge.OxygenReplacementReady),
            Feature("downed-rescue", active && owners[Capability.Downed].Owner == CapabilityOwner.External,
                "vsslssmod.downed", "API hooks only; compatible behavior must also exist on each player"),
            Feature("bloodtrail-player-loss", active && owners.MayWrite(Capability.BleedingDamage),
                "vsslssmod.bleedingvisuals", "server player loss suppression; client particles reported separately",
                "BloodTrail.src.Server.EntityBleedingBehavior"),
            Feature("progressivebleeding-player-loss", active && owners.MayWrite(Capability.BleedingDamage),
                "vsslssmod.bleedingvisuals", "server player loss suppression; animals retain external behavior",
                "ProgressiveBleeding.BleedingBehavior"),
            new("smoke-dose-integration", active && config.EnableClinicalEffects, 0, active && config.EnableClinicalEffects && MeasuredSmokeAdapter.AnyReady,
                "Real Smoke eye-cylinder plume sample gates smoke and gas exposure; absent/failed sample pauses new gas dose; native asphyxia remains external"),
            new("bed-rest-settlement", active, 0, active,
                "native bed lifecycle and calendar settlement; Comfy Beds exact-package gameplay acceptance untested")
        ];
    }

    public void WriteCompatibility(CapabilityRegistry owners, SeraphServerConfig config)
    {
        CompatibilityArchive[] known = [];
        try
        {
            known = JsonSerializer.Deserialize<CompatibilityArchive[]>(api.Assets.Get(
                new AssetLocation("vsslssmod:config/compatibility.json")).ToText()) ?? [];
        }
        catch (Exception ex) { api.Logger.Warning("[vsslssmod] Compatibility metadata unavailable: {0}", ex.Message); }
        var loaded = api.ModLoader.Mods.Select(m => new { m.Info.ModID, m.Info.Version, m.Info.Name }).ToArray();
        var integrations = loaded.Select(m =>
        {
            var exact = known.FirstOrDefault(k => string.Equals(k.ModId, m.ModID, StringComparison.OrdinalIgnoreCase) && k.Version == m.Version);
            var any = known.FirstOrDefault(k => string.Equals(k.ModId, m.ModID, StringComparison.OrdinalIgnoreCase));
            var missing = exact?.Dependencies?.Keys.Where(id => !loaded.Any(l => string.Equals(l.ModID, id, StringComparison.OrdinalIgnoreCase))).ToArray() ?? [];
            var status = exact is null ? CompatibilityStatus(m.ModID, false, false)
                : missing.Length > 0 ? "dependency-missing" : exact.Status;
            return new IntegrationStatus(m.ModID, m.Version, m.Name, status,
                exact?.Policy ?? (any is null ? "generic-passthrough" : "unknown-version-observe"));
        }).ToArray();
        var features = RuntimeFeatures(owners, config);
        var activityAdapters = ActivityCompatibility.Status(loaded.Select(m => (m.ModID, m.Version)));
        IntegrationLines = integrations.Where(i => i.Id is not ("game" or "survival" or "creative" or "vsslssmod"))
            .Select(i => i.Id + " " + i.Version + " [" + i.Status + "]")
            .Concat(features.Select(f => f.Id + ": " + (f.Ready ? "hooks-ready / 钩子就绪" : "inactive / 未启用")
                + " (" + f.InstalledHookCount + ")")).ToArray();
        File.WriteAllText(Path.Combine(directory, "compatibility-runtime.json"), JsonSerializer.Serialize(new
        {
            Package = "vsslssmod", Version = Seraph.Core.BuildInfo.Version, Assemblies = loaded,
            Integrations = integrations, Capabilities = owners.Assignments, KnownArchiveCount = known.Length,
            ArchiveInventory = known,
            DependencyDiagnostics = loaded.Select(m => new {
                Id = m.ModID, Version = m.Version,
                Missing = known.FirstOrDefault(k => string.Equals(k.ModId, m.ModID, StringComparison.OrdinalIgnoreCase) && k.Version == m.Version)
                    ?.Dependencies?.Keys.Where(id => !loaded.Any(l => string.Equals(l.ModID, id, StringComparison.OrdinalIgnoreCase))).ToArray() ?? [],
                Scope = "Presence check only; version constraints remain the game mod loader's responsibility."
            }),
            DuplicateLoadedIds = loaded.GroupBy(m => m.ModID, StringComparer.OrdinalIgnoreCase).Where(g => g.Count() > 1)
                .Select(g => new { Id = g.Key, Versions = g.Select(m => m.Version).ToArray() }),
            Mode = config.Mode, RuntimeFeatures = features,
            ActivityAdapters = activityAdapters,
            MeasuredSmoke = MeasuredSmokeAdapter.Diagnostics(),
            Conflicts = CompatibilityConflicts(loaded.Select(m => m.ModID), owners, features),
            NativeTakeoverEnabled = features.Single(f => f.Id == "native-physiology").Ready,
            FiniteInventoryMedicalEnabled = features.Single(f => f.Id == "finite-native-care").Ready,
            VerificationScope = "Installed hooks and configuration only; not full modpack gameplay acceptance.",
            ApiOnlyGaps = new[] { "external plant-contact providers", "third-party food consumption entry points",
                "server-side validation of mild mining slowdown", "smoke and coupled gas exposure use relative Real Smoke units in dimension 0 only; gas species are not exposed by the Real Smoke API",
                "weathered-world visual inspection and multiplayer interaction have not been tested",
                "smoke-dose balance and external smoke interactions require gameplay acceptance; soap can clean all open wounds",
                "Comfy Beds exact-package sleep gameplay acceptance", "full modpack sleep/smoke/riding/OpenGL acceptance" }
        }, new JsonSerializerOptions { WriteIndented = true }));
    }

    internal static string CompatibilityStatus(string id, bool exactArchive, bool missingDependency) => id.ToLowerInvariant() switch
    {
        "playerstatushud" or "playerstatusstrip" => "unsupported",
        "slowtoxvisualized" => "dependency-missing",
        _ when missingDependency => "dependency-missing",
        _ when !exactArchive => "observe-only",
        _ => "untested"
    };

    internal static string[] CompatibilityConflicts(IEnumerable<string> loaded, CapabilityRegistry owners, RuntimeFeature[] features)
    {
        var ids = loaded.ToHashSet(StringComparer.OrdinalIgnoreCase);
        var warnings = new List<string>();
        foreach (var id in new[] { "bloodtrail", "progressivebleeding" })
            if (ids.Contains(id) && owners.MayWrite(Capability.BleedingDamage)
                && !features.Any(f => f.Id == id + "-player-loss" && f.Ready
                    && f.InstalledHookCount >= (id == "bloodtrail" ? 3 : 2)))
                warnings.Add(id + ": player bleeding suppression incomplete; duplicate player loss is possible. Gameplay acceptance required.");
        if (ids.Contains("downed") && !features.Any(f => f.Id == "downed-rescue" && f.Ready))
            warnings.Add("downed: rescue bridge unavailable; native death fallback, external lifecycle unverified.");
        if (ids.Contains("realsmoke"))
            warnings.Add("realsmoke: smoke/gas exposure follows the local sampled plume; external oxygen and native smoke effects remain active.");
        if (ids.Contains("vscnservermodfix"))
            warnings.Add("vscnservermodfix: overlapping Downed rescue patches require cross-mod runtime acceptance.");
        if (ids.Contains("jaunt") && !ids.Contains("equusferus"))
            warnings.Add("jaunt: native permission and extra jump/flight adapter " + (NativeVehicleBridge.JauntReady ? "hooks-ready" : "unavailable") + "; animal speed/stamina remain Jaunt-owned; gameplay acceptance untested.");
        if (ids.Contains("equusferus"))
            warnings.Add("equusferus: only active rider control is charged; ordinary mounted motion and mount stamina remain external.");
        if (ids.Contains("shipwright"))
            warnings.Add("shipwright: optional manual-drive adapter " + (NativeVehicleBridge.ShipReady ? "hooks-ready" : "unavailable") + "; paddle/controller verified; sail power and inertia external; gameplay acceptance untested.");
        if (ids.Contains("walkableentities"))
            warnings.Add("walkableentities: platform/passenger motion is excluded from player exertion because no public propulsion event is available.");
        if (ids.Contains("carryon"))
            warnings.Add("carryon: native walkspeed/hungerrate sources retained; no guessed payload or duplicate carrying debit. Gameplay acceptance untested.");
        return warnings.ToArray();
    }

    public void Sample(string uid, string lifecycle, double dt, double calendarHours, double calendarDelta,
        double bioSeconds, double dropped, EnvironmentSample? environment, FrameworkState state,
        bool mounted, bool sleeping, bool sheltered, string behaviors, string nativeValues)
    {
        if (csvDisabled) return;
        try
        {
            if (csv is null)
            {
                var name = "probe-" + DateTime.UtcNow.ToString("yyyyMMddTHHmmssfff") + "-" + Guid.NewGuid().ToString("N")[..8] + ".csv";
                csv = new StreamWriter(Path.Combine(directory, name), false, new UTF8Encoding(false));
                csv.WriteLine("utc,uid,event,realDt_s,calendarHours_game,calendarDeltaHours_game,bio_s,dropped_s,air_C,RH_estimate,wind_mps_estimate,clo_estimate,quality,stamina,fatigue,pain,mounted,sleeping,roofSheltered_notRoom,behaviorTypes,nativeValues,exposureLedger");
            }
            if (csv.BaseStream.Position >= maxBytes) { csvDisabled = true; csv.Dispose(); csv = null; return; }
            string N(double value) => value.ToString("R", CultureInfo.InvariantCulture);
            var fields = new[] { DateTime.UtcNow.ToString("O"), uid, lifecycle, N(dt), N(calendarHours), N(calendarDelta), N(bioSeconds), N(dropped),
                environment is null ? "" : N(environment.AirTemperatureC), environment is null ? "" : N(environment.RelativeHumidity),
                environment is null ? "" : N(environment.WindSpeedMps), environment is null ? "" : N(environment.ClothingInsulationClo),
                environment?.SourceQuality.ToString() ?? "unavailable", N(state.Stamina), N(state.Fatigue), N(state.Pain), mounted.ToString(), sleeping.ToString(), sheltered.ToString(),
                behaviors.Length > 4096 ? behaviors[..4096] : behaviors, nativeValues.Length > 1024 ? nativeValues[..1024] : nativeValues, JsonSerializer.Serialize(state.Barriers.Ledger) };
            csv.WriteLine(string.Join(",", fields.Select(f => "\"" + f.Replace("\"", "\"\"") + "\"")));
            // Bound disk flush frequency, while lifecycle records are always visible promptly.
            if (++records % 10 == 0 || lifecycle != "tick") csv.Flush();
        }
        catch (Exception ex)
        {
            csvDisabled = true;
            api.Logger.Warning("[vsslssmod] CSV telemetry disabled after I/O failure: {0}", ex.Message);
            csv?.Dispose(); csv = null;
        }
    }
    public void Dispose() => csv?.Dispose();
}
