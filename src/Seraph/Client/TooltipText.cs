using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;
using Vintagestory.API.Client;
using Vintagestory.API.Config;

namespace Seraph.Client;

/// <summary>Wrap only our own text, including CJK with no spaces; preserve inline color tags.</summary>
internal static class TooltipText
{
    internal const int PanelWidth = 300;
    private readonly record struct PanelKey(string Text, string Font, double Size, Cairo.FontSlant Slant,
        Cairo.FontWeight Weight, float Scale);
    [ThreadStatic] private static Dictionary<PanelKey, string>? panelCache;
    [ThreadStatic] private static Queue<PanelKey>? panelOrder;
    internal static string Help(string key, string labelKey)
    {
        if (LocalizedText.TryGet("vsslssmod:" + key, out var value)) return value.Trim();
        return (LocalizedText.TryGet("vsslssmod:" + labelKey, out var label) ? label + ": " : "")
            + LocalizedText.Get("vsslssmod:tooltip-no-description");
    }
    internal static string Panel(string text, CairoFont font)
    {
        if (text.Length == 0) return "";
        // Keep measured native Cairo text across composer reopen/rebuild. Bound
        // the cache because live clinical details can contain changing values.
        var key = new PanelKey(text, font.Fontname, font.UnscaledFontsize, font.Slant, font.FontWeight, RuntimeEnv.GUIScale);
        panelCache ??= []; panelOrder ??= [];
        if (panelCache.TryGetValue(key, out var wrapped)) return wrapped;
        wrapped = Wrap(text, font, PanelWidth - 16);
        if (panelCache.Count >= 512) panelCache.Remove(panelOrder.Dequeue());
        panelCache[key] = wrapped; panelOrder.Enqueue(key);
        return wrapped;
    }

    internal static void ClearPanelCache() { panelCache?.Clear(); panelOrder?.Clear(); }
    internal static string Item(string text)
        // Item descriptions are also generated by the vanilla handbook on a
        // thread-pool worker. Cairo contexts are thread-affine and an access
        // violation there terminates the whole game, so this path never creates
        // or measures a Cairo font.
        => WrapApprox(text, Math.Max(100, GuiElementItemstackInfo.BoxWidth - GuiElementItemstackInfo.ItemStackSize - 66), 11);

    private static int mainThreadId;

    internal static void InitializeMainThread() => mainThreadId = Environment.CurrentManagedThreadId;
    internal static bool IsMainThread => mainThreadId != 0 && Environment.CurrentManagedThreadId == mainThreadId;

    internal static string Wrap(string text, CairoFont font, double unscaledWidth)
    {
        if (text.Length == 0) return "";
        // Character-panel tooltips are composed on the client thread. Any
        // unexpected caller (notably handbook warming) must use the safe
        // managed fallback instead of entering Cairo from a worker thread.
        if (mainThreadId != 0 && Environment.CurrentManagedThreadId != mainThreadId)
            return WrapApprox(text, unscaledWidth, 11);

        try
        {
            // CairoFont.GetTextExtents resets the font and allocates native font
            // options on every character. Set up one isolated measuring context.
            using var surface = new Cairo.ImageSurface(Cairo.Format.Argb32, 1, 1);
            using var context = new Cairo.Context(surface);
            using var options = new Cairo.FontOptions { Antialias = Cairo.Antialias.Subpixel };
            context.SetFontSize(font.UnscaledFontsize * Math.Max(.1, RuntimeEnv.GUIScale));
            context.SelectFontFace(font.Fontname, font.Slant, font.FontWeight);
            context.FontOptions = options;
            return WrapLines(text, unscaledWidth, value => context.TextExtents(value).XAdvance);
        }
        catch (Exception) { return WrapApprox(text, unscaledWidth, font.UnscaledFontsize); }
    }

    private static string WrapApprox(string text, double unscaledWidth, double fontSize)
        => WrapLines(text, unscaledWidth, value => ApproximateWidth(value, fontSize));

    private static string WrapLines(string text, double unscaledWidth, Func<string, double> measure)
    {
        var result = new StringBuilder();
        var line = "";
        var space = false;
        var width = unscaledWidth * Math.Max(.1, RuntimeEnv.GUIScale);
        bool Fits(string value) => measure(value) <= width - 2;
        void Break()
        {
            if (result.Length > 0 && result[^1] != '\n') result.Append('\n');
            line = ""; space = false;
        }
        foreach (Match token in Regex.Matches(text.Replace("\r", ""), @"<[^>]+>|\n|[^\S\n]+|[A-Za-z0-9_.,%/+−°℃-]+|[\uD800-\uDBFF][\uDC00-\uDFFF]|[^\s]"))
        {
            var value = token.Value;
            if (value[0] == '<') { result.Append(value); continue; }
            if (value == "\n") { Break(); continue; }
            if (string.IsNullOrWhiteSpace(value)) { space = line.Length > 0; continue; }
            var prefix = space ? " " : "";
            var fits = Fits(line + prefix + value);
            if (line.Length > 0 && !fits) { Break(); prefix = ""; fits = Fits(value); }
            // Most words fit whole. Measuring every successive character of
            // the same line made opening C unnecessarily expensive in Cairo.
            if (fits)
            {
                result.Append(prefix).Append(value); line += prefix + value;
                space = false; continue;
            }
            var elements = StringInfo.GetTextElementEnumerator(prefix + value);
            while (elements.MoveNext())
            {
                var character = elements.GetTextElement();
                if (line.Length > 0 && !Fits(line + character)) Break();
                if (line.Length == 0 && character == " ") continue;
                result.Append(character); line += character;
            }
            space = false;
        }
        return result.ToString().Trim();
    }

    private static double ApproximateWidth(string value, double fontSize)
    {
        var width = 0d;
        var elements = StringInfo.GetTextElementEnumerator(value);
        while (elements.MoveNext())
        {
            var element = elements.GetTextElement();
            if (element.Length == 0 || element[0] == '<') continue;
            var rune = element.EnumerateRunes().FirstOrDefault();
            if (rune.Value == 0) continue;
            width += rune.Value >= 0x2E80 || rune.Value is >= 0x1F000 and <= 0x1FAFF
                ? fontSize
                : fontSize * .56;
        }
        return width;
    }

    internal static void AppendItem(StringBuilder target, string block)
    {
        while (target.Length > 0 && char.IsWhiteSpace(target[^1])) target.Length--;
        if (target.Length > 0) target.Append('\n');
        target.Append(Item(block)).Append('\n');
    }
}
